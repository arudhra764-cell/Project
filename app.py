from pathlib import Path
import json

import joblib
import pandas as pd
import streamlit as st

MODEL_PATH = Path("models/house_price_model.joblib")
METRICS_PATH = Path("models/metrics.json")

st.set_page_config(
    page_title="HomeValue | House Price Demo",
    page_icon="🏠",
    layout="wide",
)

st.markdown(
    """
    <style>
      .block-container {max-width: 1150px; padding-top: 2rem;}
      .hero {padding: 2rem; border-radius: 18px; color: white;
        background: linear-gradient(120deg, #12355b, #247ba0);}
      .hero h1 {margin: 0 0 .4rem 0;}
      div[data-testid="stMetric"] {background: #f5f8fc; padding: 1rem;
        border-radius: 12px;}
    </style>
    """,
    unsafe_allow_html=True,
)

st.markdown(
    """<div class="hero"><h1>🏠 HomeValue</h1>
    <p>House price prediction — interactive sample app</p></div>""",
    unsafe_allow_html=True,
)
st.write("")

model = joblib.load(MODEL_PATH) if MODEL_PATH.exists() else None

with st.sidebar:
    st.header("About this sample")
    st.write("Explore how home features can be used to estimate a property price.")
    if model is None:
        st.info("Demo mode is active. Add data and train.py to use a trained model.")
    else:
        st.success("Trained model loaded.")
    st.caption("For demonstration only; not a formal property valuation.")

prediction_tab, project_tab = st.tabs(["🏡 Price estimator", "📊 Project overview"])

with prediction_tab:
    st.subheader("Enter property details")
    st.write("Adjust the example values, then select **Estimate price**.")

    with st.form("prediction_form"):
        left, right = st.columns(2)
        with left:
            area = st.number_input("Area (sq ft)", min_value=200, max_value=20000, value=3000, step=100)
            bedrooms = st.number_input("Bedrooms", min_value=1, max_value=20, value=3, step=1)
            bathrooms = st.number_input("Bathrooms", min_value=1, max_value=15, value=2, step=1)
            stories = st.number_input("Stories", min_value=1, max_value=10, value=2, step=1)
            parking = st.number_input("Parking spaces", min_value=0, max_value=10, value=1, step=1)
        with right:
            mainroad = st.selectbox("Main road access", ["yes", "no"])
            guestroom = st.selectbox("Guest room", ["yes", "no"])
            basement = st.selectbox("Basement", ["yes", "no"])
            hotwaterheating = st.selectbox("Hot water heating", ["yes", "no"])
            airconditioning = st.selectbox("Air conditioning", ["yes", "no"])
            prefarea = st.selectbox("Preferred area", ["yes", "no"])
            furnishingstatus = st.selectbox(
                "Furnishing status", ["furnished", "semi-furnished", "unfurnished"]
            )
        submitted = st.form_submit_button("Estimate price", type="primary", use_container_width=True)

    if submitted:
        house = pd.DataFrame([{
            "area": area,
            "bedrooms": bedrooms,
            "bathrooms": bathrooms,
            "stories": stories,
            "parking": parking,
            "mainroad": mainroad,
            "guestroom": guestroom,
            "basement": basement,
            "hotwaterheating": hotwaterheating,
            "airconditioning": airconditioning,
            "prefarea": prefarea,
            "furnishingstatus": furnishingstatus,
        }])

        if model is not None:
            try:
                estimate = float(model.predict(house)[0])
                estimate_label = "Model estimate"
            except (ValueError, KeyError) as error:
                st.error(f"The model's expected input columns do not match this form: {error}")
                st.stop()
        else:
            # Illustrative placeholder calculation so the sample app works without a dataset.
            estimate = (
                1_000_000
                + area * 1_500
                + bedrooms * 180_000
                + bathrooms * 220_000
                + stories * 90_000
                + parking * 100_000
                + (250_000 if prefarea == "yes" else 0)
                + (180_000 if airconditioning == "yes" else 0)
                + (120_000 if furnishingstatus == "furnished" else 0)
            )
            estimate_label = "Sample demo estimate"

        st.metric(estimate_label, f"₹{estimate:,.0f}")
        if model is None:
            st.warning("This is an illustrative demo calculation, not a trained machine-learning prediction.")
        else:
            st.success("Prediction generated by the trained model.")
        st.caption("Currency and example values should be adapted to your dataset and local market.")

with project_tab:
    st.subheader("How the project works")
    st.write(
        "The full project preprocesses numeric and categorical property features, "
        "compares regression models, and selects the model with the lowest test-set MAE."
    )
    c1, c2, c3 = st.columns(3)
    c1.metric("Input features", "12", help="Property details used by the example form")
    c2.metric("Models", "2", help="Linear Regression and Random Forest")
    c3.metric("Evaluation", "MAE · RMSE · R²")

    if METRICS_PATH.exists():
        try:
            metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
            st.markdown("#### Training results")
            st.write(f"Best model: **{metrics.get('best_model', 'Not recorded')}**")
            results = metrics.get("results", {})
            if results:
                st.dataframe(
                    [{"Model": name, **scores} for name, scores in results.items()],
                    hide_index=True,
                    use_container_width=True,
                )
        except (json.JSONDecodeError, OSError):
            st.caption("Training metrics could not be loaded.")
    else:
        st.info("Train the model with `python train.py` to show real evaluation results here.")

st.divider()
st.caption("House Price Prediction • Streamlit sample app")
